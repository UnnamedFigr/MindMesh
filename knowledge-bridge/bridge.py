@cli.command()
@click.argument("instruction_file", type=click.Path(exists=True))
@click.pass_context
def refine(ctx, instruction_file: str):
    """Propose concrete improvements to a repo instruction file."""
    cfg: BridgeConfig = ctx.obj["cfg"]
    client = get_client()
    env = get_jinja_env()
    meta = require_cache(cfg)

    target_path = Path(instruction_file)
    current_content = target_path.read_text(encoding="utf-8")

    prompt = env.get_template("refine_instruction.j2").render(
        project_name=cfg.project_name,
        tech_stack=cfg.tech_stack,
        target_file=str(target_path.name),
        current_content=current_content,
    )

    click.echo(f"Refining {target_path.name} against cached sources...")
    file_parts, gen_cfg = build_generate_config(meta, RefinementResponse.model_json_schema())
    response = client.models.generate_content(
        model=cfg.model,
        contents=file_parts + [prompt],
        config=gen_cfg,
    )

    result = RefinementResponse.model_validate_json(response.text)
    output = {
        "target_file": str(target_path),
        "deltas": [d.model_dump() for d in result.deltas],
        "unchanged_sections": result.unchanged_sections,
        "new_sections_suggested": result.new_sections_suggested,
        "refined_at": datetime.now(timezone.utc).isoformat(),
    }
    path = save_output(cfg, f"refinement_{target_path.stem}", output)

    click.echo(f"\n[OK] {len(result.deltas)} proposed changes -> {path}\n")
    for delta in result.deltas:
        click.echo(f"  [{delta.change_type.upper()}] {delta.section}")
        click.echo(f"  Rationale: {delta.rationale}")
        click.echo()
    if result.new_sections_suggested:
        click.echo(f"New sections suggested: {', '.join(result.new_sections_suggested)}")
    if result.unchanged_sections:
        click.echo(f"Already well-covered: {', '.join(result.unchanged_sections)}")


# ── sync ────────────────────────────────────────────────────────

@cli.command()
@click.option(
    "--apply",
    is_flag=True,
    default=False,
    help="Write changes to repo files. Default is dry-run (preview only).",
)
@click.pass_context
def sync(ctx, apply: bool):
    """Write extraction outputs into repo artifact files.

    Uses <!-- knowledge-bridge:start/end --> markers so re-running is safe.
    """
    cfg: BridgeConfig = ctx.obj["cfg"]

    if not cfg.sync_targets:
        raise click.ClickException(
            "No sync_targets defined in bridge.config.json. "
            "Add entries to map extraction outputs to repo files."
        )

    config_dir = BRIDGE_DIR
    changes = 0
    skipped = 0

    for target in cfg.sync_targets:
        output_data = load_output(cfg, target.extraction_type)
        if not output_data:
            click.echo(f"  [SKIP] outputs/{target.extraction_type}.json not found")
            skipped += 1
            continue

        target_path = (config_dir / Path(target.target_file)).resolve()
        if not target_path.exists():
            click.echo(f"  [SKIP] Target file not found: {target_path}")
            skipped += 1
            continue

        # Load items and apply filter
        items = output_data.get("practices") or output_data.get("anti_patterns") or []
        for key, value in target.filter.items():
            items = [
                i for i in items
                if key in i and (
                    value in i[key]
                    if isinstance(i[key], list)
                    else i[key] == value
                )
            ]

        if not items:
            click.echo(f"  [SKIP] No items matched filter for {target_path.name}")
            skipped += 1
            continue

        block = build_bridge_block(target.section, items, target.extraction_type)
        current = target_path.read_text(encoding="utf-8")
        updated = inject_or_replace_block(current, block)

        if apply:
            target_path.write_text(updated, encoding="utf-8")
            click.echo(f"  [APPLIED] {len(items)} items -> {target_path.name}")
        else:
            click.echo(f"  [DRY-RUN] Would add {len(items)} items to {target_path.name}")
            click.echo(block[:400] + ("..." if len(block) > 400 else ""))
            click.echo()

        changes += 1

    click.echo(f"\n{changes} target(s) ready, {skipped} skipped.")
    if not apply:
        click.echo("Run with --apply to write changes.")


# ── status ──────────────────────────────────────────────────────

@cli.command()
@click.pass_context
def status(ctx):
    """Show cache status and available outputs."""
    cfg: BridgeConfig = ctx.obj["cfg"]

    click.echo(f"\nProject   : {cfg.project_name}")
    click.echo(f"Model     : {cfg.model}")
    click.echo(f"Sync targets: {len(cfg.sync_targets)}")

    meta = load_cache_metadata(cfg)
    if meta:
        click.echo(f"\nCache     : {meta['cache_name']}")
        click.echo(f"  Created : {meta.get('created_at', 'unknown')}")
        click.echo(f"  Expires : {meta.get('expires_at', 'unknown')}")
        click.echo(f"  Files   : {meta.get('file_count', '?')}")
    else:
        click.echo("\nCache     : none (run 'ingest' first)")

    outputs_dir = Path(cfg.outputs_dir)
    if outputs_dir.exists():
        outputs = list(outputs_dir.glob("*.json"))
        if outputs:
            click.echo(f"\nOutputs ({len(outputs)}):")
            for p in sorted(outputs):
                click.echo(f"  {p.name}")
        else:
            click.echo("\nOutputs   : none yet")


