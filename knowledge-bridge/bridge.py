@extract.command("best-practices")
@click.option(
    "--layer",
    default=None,
    type=click.Choice(["backend", "frontend", "database", "testing", "general"]),
    help="Filter results to a specific layer.",
)
@click.pass_context
def extract_best_practices(ctx, layer):
    """Extract actionable best practices from the cached source set."""
    cfg: BridgeConfig = ctx.obj["cfg"]
    client = get_client()
    env = get_jinja_env()
    meta = require_cache(cfg)

    prompt = env.get_template("extract_best_practices.j2").render(
        project_name=cfg.project_name,
        tech_stack=cfg.tech_stack,
        layer_focus=f"Focus especially on {layer} practices." if layer else "",
    )

    click.echo("Extracting best practices from cached sources...")
    file_parts, gen_cfg = build_generate_config(meta, BestPracticesResponse.model_json_schema())
    response = client.models.generate_content(
        model=cfg.model,
        contents=file_parts + [prompt],
        config=gen_cfg,
    )

    result = BestPracticesResponse.model_validate_json(response.text)
    practices = result.practices
    if layer:
        practices = [p for p in practices if layer in p.applicable_to]

    output_key = f"best_practices{'_' + layer if layer else ''}"
    output = {
        "practices": [p.model_dump() for p in practices],
        "source_summary": result.source_summary,
        "gaps_noted": result.gaps_noted,
        "mode": "cached" if meta.get("use_cache") else "per-call",
        "extracted_at": datetime.now(timezone.utc).isoformat(),
        "tokens_used": (
            response.usage_metadata.total_token_count
            if response.usage_metadata else None
        ),
    }
    path = save_output(cfg, output_key, output)

    click.echo(f"\n[OK] {len(practices)} best practices -> {path}")
    click.echo(f"\nSource summary: {result.source_summary[:200]}...")
    click.echo("\nTop practices:")
    for p in practices[:6]:
        click.echo(f"  [{p.category}] {p.rule}")
    if len(practices) > 6:
        click.echo(f"  ... and {len(practices) - 6} more. See {path}")
    if result.gaps_noted:
        click.echo(f"\nGaps noted: {', '.join(result.gaps_noted)}")


