# ── Constants ───────────────────────────────────────────────────

PROMPTS_DIR = BRIDGE_DIR / "prompts"

# Markers used by sync to find/replace the generated block in repo files
MARKER_START = "<!-- knowledge-bridge:start -->"
MARKER_END = "<!-- knowledge-bridge:end -->"

# Mime type mapping for sources
MIME_TYPES = {
    ".pdf": "application/pdf",
    ".txt": "text/plain",
    ".md": "text/plain",
    ".html": "text/html",
    ".htm": "text/html",
    ".json": "application/json",
    ".csv": "text/csv",
}


# ── Helpers ─────────────────────────────────────────────────────

def get_client() -> genai.Client:
    return genai.Client(api_key=get_api_key())


def get_jinja_env() -> Environment:
    return Environment(loader=FileSystemLoader(str(PROMPTS_DIR)))


def cache_metadata_path(cfg: BridgeConfig) -> Path:
    return Path(cfg.cache_dir) / "cache_metadata.json"


def load_cache_metadata(cfg: BridgeConfig) -> Optional[dict]:
    path = cache_metadata_path(cfg)
    if not path.exists():
        return None
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def save_cache_metadata(cfg: BridgeConfig, metadata: dict) -> None:
    cache_dir = Path(cfg.cache_dir)
    cache_dir.mkdir(parents=True, exist_ok=True)
    with open(cache_metadata_path(cfg), "w", encoding="utf-8") as f:
        json.dump(metadata, f, indent=2)


def save_output(cfg: BridgeConfig, name: str, data: dict) -> Path:
    outputs_dir = Path(cfg.outputs_dir)
    outputs_dir.mkdir(parents=True, exist_ok=True)
    path = outputs_dir / f"{name}.json"
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, default=str)
    return path


def load_output(cfg: BridgeConfig, name: str) -> Optional[dict]:
    path = Path(cfg.outputs_dir) / f"{name}.json"
    if not path.exists():
        return None
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def model_name_for_cache(model: str) -> str:
    """Gemini caches.create requires 'models/' prefix."""
    return model if model.startswith("models/") else f"models/{model}"


def build_bridge_block(section_title: str, items: list, item_type: str) -> str:
    """Build the knowledge-bridge marker block for sync insertion."""
    lines = [
        MARKER_START,
        "",
        f"## {section_title} _(auto-generated by knowledge-bridge)_",
        "",
    ]
    for item in items:
        if item_type == "best_practices":
            lines.append(f"- **[{item['category']}]** {item['rule']}")
            if item.get("rationale"):
                lines.append(f"  > {item['rationale']}")
        elif item_type == "anti_patterns":
            lines.append(f"- ❌ **Avoid:** {item['pattern']}")
            lines.append(f"  - Why: {item['why_bad']}")
            lines.append(f"  - ✓ Instead: {item['preferred_alternative']}")
        lines.append("")
    lines.append(MARKER_END)
    return "\n".join(lines)


def inject_or_replace_block(content: str, block: str) -> str:
    """Replace existing bridge block or append at end of file."""
    if MARKER_START in content and MARKER_END in content:
        start = content.index(MARKER_START)
        end = content.index(MARKER_END) + len(MARKER_END)
        return content[:start] + block + content[end:]
    return content.rstrip() + "\n\n" + block + "\n"


def require_cache(cfg: BridgeConfig) -> dict:
    """Load ingest metadata or exit with helpful message."""
    meta = load_cache_metadata(cfg)
    if not meta:
        raise click.ClickException(
            "No ingest metadata found. Run:  python bridge.py ingest"
        )
    return meta


def build_generate_config(
    meta: dict,
    response_schema,
) -> tuple[list, types.GenerateContentConfig]:
    """
    Return (contents_parts, GenerateContentConfig) using either:
      - explicit context cache (paid tier)
      - uploaded file URIs (free tier, re-sent each call)

    The caller should prepend the prompt string to contents_parts.
    """
    if meta.get("use_cache") and meta.get("cache_name"):
        # Paid tier: files already in cache, prompt is the only new content
        parts: list = []
        gen_cfg = types.GenerateContentConfig(
            cached_content=meta["cache_name"],
            response_mime_type="application/json",
            response_json_schema=response_schema,
        )
    else:
        # Free tier: reference uploaded files by URI (re-charged per call)
        parts = [
            types.Part.from_uri(
                file_uri=f["uri"],
                mime_type=f["mime_type"],
            )
            for f in meta.get("files", [])
            if f.get("uri")
        ]
        gen_cfg = types.GenerateContentConfig(
            response_mime_type="application/json",
            response_json_schema=response_schema,
        )
    return parts, gen_cfg


