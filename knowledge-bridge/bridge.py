# ── ingest ──────────────────────────────────────────────────────

@cli.command()
@click.pass_context
def ingest(ctx):
    """Upload source files to Gemini and create a context cache."""
    cfg: BridgeConfig = ctx.obj["cfg"]
    client = get_client()
    sources_dir = Path(cfg.sources_dir)

    source_files = [
        f for f in sources_dir.rglob("*")
        if f.is_file() and not f.name.startswith(".")
    ]
    if not source_files:
        raise click.ClickException(
            f"No source files found in {sources_dir.resolve()}\n"
            "Add PDFs, .txt, or .md files and try again."
        )

    # ── Upload files ────────────────────────────────────────────
    click.echo(f"\nUploading {len(source_files)} file(s) to Gemini Files API...")
    uploaded = []
    for fpath in source_files:
        mime = MIME_TYPES.get(fpath.suffix.lower(), "text/plain")
        click.echo(f"  >> {fpath.name} ({mime})")

        uploaded_file = client.files.upload(
            file=fpath,
            config={"mime_type": mime, "display_name": fpath.name},
        )
        # Wait for processing (relevant for large PDFs)
        retries = 0
        while str(uploaded_file.state) in ("FileState.PROCESSING", "PROCESSING") and retries < 60:
            time.sleep(3)
            uploaded_file = client.files.get(name=uploaded_file.name)
            retries += 1

        if str(uploaded_file.state) in ("FileState.FAILED", "FAILED"):
            click.echo(f"  [SKIP] {fpath.name} -- upload failed, skipping")
            continue

        uploaded.append(uploaded_file)
        click.echo(f"  [OK] {fpath.name}")

    if not uploaded:
        raise click.ClickException("No files were successfully uploaded.")

    # ── Try to create explicit context cache (requires paid tier) ──
    use_cache = False
    cache_name = None
    try:
        click.echo(f"\nCreating context cache (TTL: {cfg.cache_ttl_seconds}s)...")
        cache = client.caches.create(
            model=model_name_for_cache(cfg.model),
            config=types.CreateCachedContentConfig(
                display_name=f"{cfg.project_name} — knowledge sources",
                system_instruction=(
                    f"You are a technical knowledge expert analyzing engineering sources "
                    f"for the {cfg.project_name} project ({cfg.tech_stack}). "
                    f"Answer only from the provided source documents. "
                    f"If information is not in the sources, say so explicitly."
                ),
                contents=uploaded,
                ttl=f"{cfg.cache_ttl_seconds}s",
            ),
        )
        use_cache = True
        cache_name = cache.name
        click.echo(f"  [OK] Cache created: {cache.name}")
        click.echo(f"  Expires: {cache.expire_time}")
    except Exception as e:
        err = str(e)
        if "FreeTier" in err or "RESOURCE_EXHAUSTED" in err:
            click.echo(
                "  [!] Context caching unavailable on free tier -- "
                "files will be re-sent per call (still works, just less efficient)."
            )
        else:
            click.echo(f"  [!] Cache creation failed ({e}) -- falling back to per-call mode.")

    metadata = {
        "use_cache": use_cache,
        "cache_name": cache_name,
        "model": cfg.model,
        "project_name": cfg.project_name,
        "files": [
            {
                "name": f.name,
                "display_name": getattr(f, "display_name", f.name),
                "uri": getattr(f, "uri", None),
                "mime_type": getattr(f, "mime_type", "text/plain"),
            }
            for f in uploaded
        ],
        "created_at": datetime.now(timezone.utc).isoformat(),
        "file_count": len(uploaded),
    }
    save_cache_metadata(cfg, metadata)

    click.echo(f"\n[OK] Ingest complete -- {len(uploaded)} file(s) ready")
    if use_cache:
        click.echo(f"  Mode: cached (efficient - files sent once)")
    else:
        click.echo(f"  Mode: per-call (free tier - files included in each request)")
    click.echo(f"\nNext: python bridge.py extract best-practices")


